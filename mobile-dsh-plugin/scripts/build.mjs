import {readFile, writeFile, mkdir} from "node:fs/promises";
import {createCore} from "../src/core.js";
import {createClient} from "../src/client.js";

const css = await readFile(new URL("../src/mobile.css", import.meta.url), "utf8");
const manifest = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
const bundle = `// Generated by scripts/build.mjs; source lives in src/.\n` +
  `window.__ModuleLoader__.load({id:${JSON.stringify(manifest.name)},factory:function(require){\n` +
  `const core=(${createCore.toString()})(window);\n` +
  `return (${createClient.toString()})(require("react"),` +
  `require("@deepseek-ai/dsh-client-ui-primitives"),core,${JSON.stringify(css)},window);\n}});\n`;
await mkdir(new URL("../lib/", import.meta.url), {recursive: true});
await writeFile(new URL("../lib/client.js", import.meta.url), bundle);
console.log("Built lazy DSH client module (no network or third-party build dependencies).");
