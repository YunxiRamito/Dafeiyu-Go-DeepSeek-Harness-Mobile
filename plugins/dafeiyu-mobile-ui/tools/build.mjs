import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createDafeiyuMobileContext } from '../client/context.js';
import { createDafeiyuMobileUiPlugin } from '../client/index.js';
import { createDafeiyuMobileFooter } from '../client/host-footer.js';
import { createDafeiyuStartup } from '../client/startup.js';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const packageJson = JSON.parse(await readFile(resolve(packageRoot, 'package.json'), 'utf8'));
const cssPath = resolve(packageRoot, 'client/styles.css');
let cssText;
try {
  cssText = await readFile(cssPath, 'utf8');
} catch (error) {
  throw new Error(`Missing ${cssPath}; the mobile CSS must be supplied before bundling: ${error.message}`);
}

const output = `// Generated by tools/build.mjs; source lives in client/.\n` +
  `window.__ModuleLoader__.load({\n` +
  `  id: ${JSON.stringify(packageJson.name)},\n` +
  `  factory(require) {\n` +
  `    const createContext = (${createDafeiyuMobileContext.toString()});\n` +
  `    const createPlugin = (${createDafeiyuMobileUiPlugin.toString()});\n` +
  `    const createFooter = (${createDafeiyuMobileFooter.toString()});\n` +
  `    const createStartup = (${createDafeiyuStartup.toString()});\n` +
  `    return createPlugin(createContext(globalThis), ${JSON.stringify(cssText)}, createFooter, createStartup);\n` +
  `  },\n` +
  `});\n`;

await writeFile(resolve(packageRoot, 'client/client.js'), output, 'utf8');
process.stdout.write(`Built ${packageJson.name} ${packageJson.version} (${Buffer.byteLength(output)} bytes)\n`);
